"""Persistence port: task fences and journal writes must share a transaction.

SQLite is a development implementation, not a required production database.
An implementation must not grant leases or restore outputs from memory fallback.
"""
from typing import Protocol


class HarnessJournal(Protocol):
    task_contract_ref: str
    @property
    def storage_identity(self) -> str: ...
    def approve(self, actor, stage, *, action, proposal_digest): ...
    def find(self, actor, run_id, attempt_id): ...
    def enqueue(self, actor, invocation, *, model_calls): ...
    def pending(self, actor, project_id, *, limit=32): ...
    def claim(self, actor, handle, *, lease_seconds=30): ...
    def renew(self, actor, handle, token, *, lease_seconds=30): ...
    def guard(self, actor, handle, token): ...
    def model_admit(self, actor, handle, token, sequence): ...
    def tool_call(self, actor, handle, token, definition, arguments, fingerprint, handler): ...
    def pending_outputs(self, actor, handle, token): ...
    def finish(self, actor, handle, token, *, code=None): ...
    def cancel(self, actor, handle): ...
    def recover(self, actor, handle): ...
    def read(self, actor, handle, *, after_cursor=0): ...


class StageReviewStore(Protocol):
    """Draft/action writes and stage approval/enqueue must commit atomically."""
    @property
    def storage_identity(self) -> str: ...
    def prepared(self, actor, task_id, key, fingerprint): ...
    def save(self, actor, task_id, key, fingerprint, review): ...
    def get(self, actor, task_id, draft_id, *, cleanup=False): ...
    def list(self, actor, task, limit): ...
    def act(self, actor, task_id, draft_id, operation, key, body): ...
    def invocation(self, row, review): ...
